// The newtab sync check is only worth having if it actually notices drift, so
// it is exercised against a throwaway copy of the repo layout.

import { test, beforeEach, afterEach } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { copyFile, mkdir, mkdtemp, readFile, rm, stat, unlink, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { checkNewtab } from '../../scripts/check-newtab.mjs';

const REPO = fileURLToPath(new URL('../..', import.meta.url));

const PAGE = `<!DOCTYPE html>
<html lang="en">
<head>
<title>Fixture</title>
<script src="vendor.js"></script>
</head>
<body>
<p id="hello">hi</p>
<script>
(function () { document.getElementById('hello').textContent = 'one'; })();
</script>
<script>
(() => { console.log('two'); })();
</script>
</body>
</html>
`;

let root;

async function build() {
  const run = spawnSync('python3', ['build-newtab.py'], { cwd: path.join(root, 'extension'), encoding: 'utf8' });
  assert.equal(run.status, 0, run.stderr);
}

beforeEach(async () => {
  root = await mkdtemp(path.join(tmpdir(), 'simplehome-check-test-'));
  await mkdir(path.join(root, 'extension'));
  await writeFile(path.join(root, 'index.html'), PAGE);
  await copyFile(path.join(REPO, 'extension', 'build-newtab.py'), path.join(root, 'extension', 'build-newtab.py'));
  await build();
});

afterEach(async () => {
  await rm(root, { recursive: true, force: true });
});

test('passes when the generated files match index.html', async () => {
  assert.deepEqual(await checkNewtab(root), []);
});

test('flags newtab.js when a script in index.html changed after the last build', async () => {
  await writeFile(path.join(root, 'index.html'), PAGE.replace("'one'", "'uno'"));
  const problems = await checkNewtab(root);
  assert.deepEqual(
    problems.map((p) => p.file),
    ['newtab.js'],
  );
  assert.match(problems[0].problem, /expected .*uno.*, found .*one/);
});

test('flags newtab.html when the markup changed after the last build', async () => {
  await writeFile(path.join(root, 'index.html'), PAGE.replace('<p id="hello">hi</p>', '<p id="hello">hello</p>'));
  assert.deepEqual(
    (await checkNewtab(root)).map((p) => p.file),
    ['newtab.html'],
  );
});

test('flags a generated file that was hand-edited or deleted', async () => {
  await writeFile(path.join(root, 'extension', 'newtab.js'), 'tweaked by hand\n');
  await unlink(path.join(root, 'extension', 'newtab.html'));
  assert.deepEqual(await checkNewtab(root), [
    { file: 'newtab.html', problem: 'missing' },
    {
      file: 'newtab.js',
      problem:
        'differs from line 1: expected "// Generated by build-newtab.py from ../index.html — edit that file, not this one.", found "tweaked by hand"',
    },
  ]);
});

test('never writes to the checked repo', async () => {
  const files = ['index.html', 'extension/newtab.html', 'extension/newtab.js'];
  await writeFile(path.join(root, 'index.html'), PAGE.replace("'one'", "'uno'"));
  const before = await Promise.all(
    files.map(async (f) => [await readFile(path.join(root, f), 'utf8'), (await stat(path.join(root, f))).mtimeMs]),
  );
  await checkNewtab(root);
  const after = await Promise.all(
    files.map(async (f) => [await readFile(path.join(root, f), 'utf8'), (await stat(path.join(root, f))).mtimeMs]),
  );
  assert.deepEqual(after, before);
});

test('reports the generator failing rather than passing silently', async () => {
  await writeFile(path.join(root, 'index.html'), '<!DOCTYPE html><title>no scripts</title>');
  await assert.rejects(checkNewtab(root), /build-newtab\.py exited with 1: error: no inline <script> found/);
});
